// Command genendpoints writes the list of endpoints that the llama-server README documents as headings, one
// "METHOD PATH" line per endpoint, preceded by a comment naming the source. It fails unless it finds exactly the
// expected number of endpoints, so that a heading the pattern misses cannot shrink the list silently.
//
// Usage:
//
//	go run ./internal/cmd/genendpoints -o testdata/endpoints.v1.1.0.txt
//	go run ./internal/cmd/genendpoints -readme README.md -o testdata/endpoints.v1.1.0.txt
package main

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"time"
)

const (
	// commit is the llama.cpp commit of tag v1.1.0.
	commit = "171527522610996f5f0acf12334e185156ca8f44"
	// readmeURL is the server README at that commit.
	readmeURL = "https://raw.githubusercontent.com/ggml-org/llama.cpp/" + commit + "/tools/server/README.md"
	// wantEndpoints is the number of endpoint headings of the README at that commit.
	wantEndpoints = 38
)

// heading matches an endpoint heading such as "### POST `/completion`: ..." or "### **GET** `/props`: ...".
var heading = regexp.MustCompile("^### (?:\\*\\*)?(GET|POST|PUT|PATCH|DELETE|WebSocket)(?:\\*\\*)? `([^`]+)`")

func main() {
	log.SetFlags(0)
	log.SetPrefix("genendpoints: ")
	out := flag.String("o", "", "output file (default standard output)")
	readme := flag.String("readme", "", "read the README from this file instead of downloading it")
	flag.Parse()

	src, err := load(*readme)
	if err != nil {
		log.Fatal(err)
	}
	lines, err := extract(src)
	if err != nil {
		log.Fatal(err)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# %s (llama.cpp v1.1.0, commit %s); generated by internal/cmd/genendpoints, do not edit\n", readmeURL, commit)
	for _, l := range lines {
		buf.WriteString(l)
		buf.WriteByte('\n')
	}
	if *out == "" {
		_, err = os.Stdout.Write(buf.Bytes())
	} else {
		err = os.WriteFile(*out, buf.Bytes(), 0o644)
	}
	if err != nil {
		log.Fatal(err)
	}
}

// load returns the README from path, or downloads it when path is empty.
func load(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, readmeURL, nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", readmeURL, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// extract returns the "METHOD PATH" lines of the endpoint headings in document order.
func extract(src []byte) ([]string, error) {
	var lines []string
	sc := bufio.NewScanner(bytes.NewReader(src))
	sc.Buffer(make([]byte, 0, 64<<10), 1<<20)
	for sc.Scan() {
		if m := heading.FindStringSubmatch(sc.Text()); m != nil {
			lines = append(lines, m[1]+" "+m[2])
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(lines) != wantEndpoints {
		return nil, errors.Join(
			fmt.Errorf("found %d endpoint headings, want %d", len(lines), wantEndpoints),
			fmt.Errorf("found: %q", lines),
		)
	}
	return lines, nil
}
